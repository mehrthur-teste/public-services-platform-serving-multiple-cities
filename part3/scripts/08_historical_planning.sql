\copy stage_maintenance FROM 'part3/.runtime/maintenance.csv' WITH CSV HEADER
CREATE TEMP TABLE stage_environmental(day DATE,city_id UUID,metric TEXT,unit TEXT,samples BIGINT,minimum DOUBLE PRECISION,maximum DOUBLE PRECISION,average DOUBLE PRECISION) ON COMMIT DROP;
