CREATE SCHEMA IF NOT EXISTS historical_planning;
CREATE TABLE IF NOT EXISTS historical_planning.dim_date (
 date_key INTEGER PRIMARY KEY, calendar_date DATE NOT NULL UNIQUE,
 year_number SMALLINT NOT NULL, month_number SMALLINT NOT NULL CHECK(month_number BETWEEN 1 AND 12),
 day_of_week SMALLINT NOT NULL CHECK(day_of_week BETWEEN 1 AND 7),
 CHECK(date_key=to_char(calendar_date,'YYYYMMDD')::integer),
 CHECK(year_number=extract(year FROM calendar_date) AND month_number=extract(month FROM calendar_date)
 AND day_of_week=extract(isodow FROM calendar_date))
);
CREATE TABLE IF NOT EXISTS historical_planning.dim_city (
 city_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_city_id UUID NOT NULL UNIQUE, city_name TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS historical_planning.dim_facility (
 facility_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_facility_id UUID NOT NULL UNIQUE, city_key BIGINT NOT NULL REFERENCES historical_planning.dim_city(city_key),
 facility_name TEXT NOT NULL, facility_type TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS historical_planning.fact_traffic_summary (
 traffic_summary_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 date_key INTEGER NOT NULL REFERENCES historical_planning.dim_date(date_key),
 city_key BIGINT NOT NULL REFERENCES historical_planning.dim_city(city_key),
 source_road_id UUID NOT NULL, speed_sample_count BIGINT NOT NULL CHECK(speed_sample_count>=0),
 average_speed_kmh DOUBLE PRECISION CHECK(average_speed_kmh>=0),
 average_occupancy_percentage DOUBLE PRECISION CHECK(average_occupancy_percentage BETWEEN 0 AND 100),
 loaded_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(date_key,city_key,source_road_id)
);
CREATE TABLE IF NOT EXISTS historical_planning.fact_environmental_summary (
 environmental_summary_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 date_key INTEGER NOT NULL REFERENCES historical_planning.dim_date(date_key),
 city_key BIGINT NOT NULL REFERENCES historical_planning.dim_city(city_key), metric TEXT NOT NULL, unit TEXT NOT NULL,
 sample_count BIGINT NOT NULL CHECK(sample_count>=0),
 minimum_value DOUBLE PRECISION, maximum_value DOUBLE PRECISION, average_value DOUBLE PRECISION,
 loaded_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(date_key,city_key,metric,unit),
 CHECK(minimum_value<=maximum_value), CHECK(average_value BETWEEN minimum_value AND maximum_value)
);
CREATE TABLE IF NOT EXISTS historical_planning.fact_service_performance (
 service_summary_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 date_key INTEGER NOT NULL REFERENCES historical_planning.dim_date(date_key),
 city_key BIGINT NOT NULL REFERENCES historical_planning.dim_city(city_key), request_category TEXT NOT NULL,
 submitted_count BIGINT NOT NULL CHECK(submitted_count>=0), resolved_count BIGINT NOT NULL CHECK(resolved_count>=0),
 total_resolution_seconds NUMERIC(20,0) NOT NULL CHECK(total_resolution_seconds>=0),
 loaded_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(date_key,city_key,request_category)
);
CREATE TABLE IF NOT EXISTS historical_planning.fact_maintenance_cost (
 maintenance_summary_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 date_key INTEGER NOT NULL REFERENCES historical_planning.dim_date(date_key),
 facility_key BIGINT NOT NULL REFERENCES historical_planning.dim_facility(facility_key),
 currency_code CHAR(3) NOT NULL CHECK(currency_code ~ '^[A-Z]{3}$'),
 cost_item_count BIGINT NOT NULL CHECK(cost_item_count>=0), total_cost NUMERIC(18,2) NOT NULL CHECK(total_cost>=0),
 loaded_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(date_key,facility_key,currency_code)
);

CREATE TEMP TABLE stage_cities(city_id UUID,name TEXT) ON COMMIT DROP;
\copy stage_cities FROM 'part3/.runtime/cities.csv' WITH CSV HEADER
CREATE TEMP TABLE stage_facilities(facility_id UUID,city_id UUID,name TEXT,facility_type TEXT) ON COMMIT DROP;
\copy stage_facilities FROM 'part3/.runtime/facilities.csv' WITH CSV HEADER
CREATE TEMP TABLE stage_traffic(day DATE,city_id UUID,road_id UUID,samples BIGINT,speed DOUBLE PRECISION,occupancy DOUBLE PRECISION) ON COMMIT DROP;
\copy stage_traffic FROM 'part3/.runtime/traffic.csv' WITH CSV HEADER
CREATE TEMP TABLE stage_service(day DATE,city_id UUID,category TEXT,submitted BIGINT,resolved BIGINT,seconds NUMERIC) ON COMMIT DROP;
\copy stage_service FROM 'part3/.runtime/service.csv' WITH CSV HEADER
