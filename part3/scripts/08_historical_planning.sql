-- Validate imported lineage before loading dimensions/facts.
DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM stage_facilities f LEFT JOIN stage_cities c USING(city_id) WHERE c.city_id IS NULL)
 OR EXISTS(SELECT 1 FROM stage_traffic t LEFT JOIN stage_cities c USING(city_id) WHERE c.city_id IS NULL)
 OR EXISTS(SELECT 1 FROM stage_environmental e LEFT JOIN stage_cities c USING(city_id) WHERE c.city_id IS NULL)
 OR EXISTS(SELECT 1 FROM stage_service s LEFT JOIN stage_cities c USING(city_id) WHERE c.city_id IS NULL)
 OR EXISTS(SELECT 1 FROM stage_maintenance m LEFT JOIN stage_facilities f USING(facility_id) WHERE f.facility_id IS NULL)
 THEN RAISE EXCEPTION 'Unmapped integration identifier'; END IF;
END $$;
INSERT INTO historical_planning.dim_date(date_key,calendar_date,year_number,month_number,day_of_week)
SELECT to_char(day,'YYYYMMDD')::int,day,extract(year FROM day),extract(month FROM day),extract(isodow FROM day)
FROM (SELECT day FROM stage_traffic UNION SELECT day FROM stage_environmental UNION SELECT day FROM stage_service UNION SELECT day FROM stage_maintenance UNION SELECT DATE '2026-10-24') dates
ON CONFLICT DO NOTHING;
INSERT INTO historical_planning.dim_city(source_city_id,city_name)
SELECT city_id,name FROM stage_cities
ON CONFLICT(source_city_id) DO UPDATE SET city_name=EXCLUDED.city_name;
INSERT INTO historical_planning.dim_facility(source_facility_id,city_key,facility_name,facility_type)
SELECT f.facility_id,c.city_key,f.name,f.facility_type FROM stage_facilities f
JOIN historical_planning.dim_city c ON c.source_city_id=f.city_id
ON CONFLICT(source_facility_id) DO UPDATE SET city_key=EXCLUDED.city_key,facility_name=EXCLUDED.facility_name,facility_type=EXCLUDED.facility_type;
INSERT INTO historical_planning.fact_traffic_summary(date_key,city_key,source_road_id,speed_sample_count,average_speed_kmh,average_occupancy_percentage)
SELECT to_char(t.day,'YYYYMMDD')::int,c.city_key,t.road_id,t.samples,t.speed,t.occupancy
FROM stage_traffic t JOIN historical_planning.dim_city c ON c.source_city_id=t.city_id
ON CONFLICT(date_key,city_key,source_road_id) DO UPDATE SET speed_sample_count=EXCLUDED.speed_sample_count,average_speed_kmh=EXCLUDED.average_speed_kmh,average_occupancy_percentage=EXCLUDED.average_occupancy_percentage,loaded_at=now();
INSERT INTO historical_planning.fact_environmental_summary(date_key,city_key,metric,unit,sample_count,minimum_value,maximum_value,average_value)
SELECT to_char(e.day,'YYYYMMDD')::int,c.city_key,e.metric,e.unit,e.samples,e.minimum,e.maximum,e.average
FROM stage_environmental e JOIN historical_planning.dim_city c ON c.source_city_id=e.city_id
ON CONFLICT(date_key,city_key,metric,unit) DO UPDATE SET sample_count=EXCLUDED.sample_count,minimum_value=EXCLUDED.minimum_value,maximum_value=EXCLUDED.maximum_value,average_value=EXCLUDED.average_value,loaded_at=now();
INSERT INTO historical_planning.fact_service_performance(date_key,city_key,request_category,submitted_count,resolved_count,total_resolution_seconds)
SELECT to_char(s.day,'YYYYMMDD')::int,c.city_key,s.category,s.submitted,s.resolved,s.seconds
FROM stage_service s JOIN historical_planning.dim_city c ON c.source_city_id=s.city_id
ON CONFLICT(date_key,city_key,request_category) DO UPDATE SET submitted_count=EXCLUDED.submitted_count,resolved_count=EXCLUDED.resolved_count,total_resolution_seconds=EXCLUDED.total_resolution_seconds,loaded_at=now();
INSERT INTO historical_planning.fact_maintenance_cost(date_key,facility_key,currency_code,cost_item_count,total_cost)
SELECT to_char(m.day,'YYYYMMDD')::int,f.facility_key,m.currency_code,m.items,m.total
FROM stage_maintenance m JOIN historical_planning.dim_facility f ON f.source_facility_id=m.facility_id
ON CONFLICT(date_key,facility_key,currency_code) DO UPDATE SET cost_item_count=EXCLUDED.cost_item_count,total_cost=EXCLUDED.total_cost,loaded_at=now();

